import js from '@eslint/js'
import globals from 'globals'
import reactHooks from 'eslint-plugin-react-hooks'
import reactRefresh from 'eslint-plugin-react-refresh'
import tseslint from 'typescript-eslint'
import { defineConfig, globalIgnores } from 'eslint/config'
import baseline from './eslint.baseline.json' with { type: 'json' }

// Complexity and size limits for production code (JAN-259, JAN-264). Stories,
// tests, fixtures, test helpers and generated types are exempt.
const LIMITS = {
  complexity: 15,
  'max-depth': 4,
  'max-nested-callbacks': 4,
  'max-lines': 400,
  'max-lines-per-function': 150,
}
const SIZE_OPTIONS = { skipBlankLines: true, skipComments: true }

const ruleOptions = (rule, max) =>
  rule === 'max-lines' || rule === 'max-lines-per-function' ? ['error', { max, ...SIZE_OPTIONS }] : ['error', max]

const PRODUCTION_FILES = ['src/**/*.{ts,tsx}']
const NOT_PRODUCTION = [
  'src/**/*.stories.tsx',
  'src/**/*.{test,spec}.{ts,tsx}',
  'src/**/*Fixtures.ts',
  'src/test/**',
  'src/generated/**',
]

export default defineConfig([
  // `storybook-static` is generated by `npm run build-storybook`; linting its
  // bundled vendor code produced unrelated errors on any machine that built it.
  globalIgnores(['dist', 'storybook-static', 'coverage']),
  {
    files: ['**/*.{ts,tsx}'],
    extends: [
      js.configs.recommended,
      tseslint.configs.recommended,
      reactHooks.configs.flat.recommended,
      reactRefresh.configs.vite,
    ],
    languageOptions: {
      ecmaVersion: 2020,
      globals: globals.browser,
    },
  },
  {
    files: PRODUCTION_FILES,
    ignores: NOT_PRODUCTION,
    rules: Object.fromEntries(Object.entries(LIMITS).map(([rule, max]) => [rule, ruleOptions(rule, max)])),
  },
  // Hotspots that already exceeded a limit when it was introduced are held at their
  // measured size (eslint.baseline.json): they may shrink, not grow. Lower an entry
  // when its file improves; delete it once the file is within the limit. The follow-up
  // list is "Baselined hotspots" in docs/docs/tech-spec/architecture-overview.md.
  ...Object.entries(baseline).map(([file, rules]) => ({
    files: [file],
    rules: Object.fromEntries(Object.entries(rules).map(([rule, max]) => [rule, ruleOptions(rule, max)])),
  })),
])
