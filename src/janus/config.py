    @field_validator("allowed_origins", mode="before")
    @classmethod
    def parse_origins(cls, v: object) -> list[str]:
        """Normalizes comma-separated origins from the environment."""
        if isinstance(v, str):
            origins = [o.strip() for o in v.split(",") if o.strip()]
        elif v is None:
            origins = []
        elif isinstance(v, list | tuple | set):
            origins = list(v)
        else:
            raise ValueError("allowed_origins must be a comma-separated string or iterable of origins.")
        return [_normalize_allowed_origin(str(origin)) for origin in origins]

    @field_validator("allowed_hosts", mode="before")
    @classmethod
    def parse_allowed_hosts(cls, v: object) -> list[str]:
        """Normalizes comma-separated Host allowlists from the environment."""
        if isinstance(v, str):  # noqa: SIM108
            hosts = [host.strip() for host in v.split(",") if host.strip()]
        else:
            hosts = v  # type: ignore[assignment]

        return [_normalize_allowed_host(str(host)) for host in hosts]

    @field_validator("database_url", mode="before")
    @classmethod
    def validate_sqlite_url(cls, v: object) -> object:
        """Catches the common mistake of writing sqlite:///path instead of sqlite:////path for absolute paths.

        sqlite:///./relative.db  is correct for a relative path.
        sqlite:////home/you/db   is correct for an absolute path.
        sqlite:///home/you/db    is WRONG — SQLAlchemy treats it as a relative path
                                 named ``home/you/db`` under the current working directory.
        """
        if isinstance(v, str) and re.match(r"^sqlite:///[a-zA-Z][^/]*/", v):
            corrected = f"sqlite:////{v[len('sqlite:///') :]}"
            raise ValueError(
                f"database_url looks like an absolute path written with three slashes.\n"
                f"  Got:      {v}\n"
                f"  Correct:  {corrected}\n"
                "Use four slashes for absolute SQLite paths (sqlite:////path) "
                "or three slashes with ./ for relative paths (sqlite:///./path)."
            )
        return v

    @field_validator("fernet_key_path", "log_file_path", "image_storage_dir", mode="before")
    @classmethod
    def validate_absolute_path(cls, v: object) -> Path:
        """Ensures runtime file paths are explicit absolute paths."""
        path = v if isinstance(v, Path) else Path(str(v)).expanduser()
        if not path.is_absolute():
            raise ValueError("Runtime file paths must use absolute persistent paths.")
        return path

    @property
    def is_placeholder_key(self) -> bool:
        """Returns True when the secret key is still the default placeholder."""
        return self.janus_secret_key == _DEFAULT_SECRET

    def require_secret_key(self) -> None:
        """Raises RuntimeError if the secret key is still the default placeholder.

        Call this from startup paths (``janus start``, API lifespan) rather than
        at import time so that ``janus --help`` and ``janus config init`` work for
        new users who haven't configured a key yet.
        """
        if self.is_placeholder_key:
            config_path = get_config_file_path()
            raise RuntimeError(
                "JANUS_SECRET_KEY is still the default placeholder. "
                f"Set a secure random value in {config_path} "
                "under the key 'secret_key', or export JANUS_SECRET_KEY before "
                "starting Janus.\n\n"
                "Quick start:\n"
                "  janus config init          # create config file\n"
                f"  # then edit {config_path} and set secret_key\n"
                "  janus start                # start the server"
            )

