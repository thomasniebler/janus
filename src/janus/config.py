def mask_database_url(url: str) -> str:
    """Masks the password component of a database URL.

    Args:
        url: A database connection string that may contain credentials.

    Returns:
        The connection string with any password replaced by ``***``.
    """
    return re.sub(r"(?<=://)([^:@]+):([^@]+)@", r"\1:***@", url)


