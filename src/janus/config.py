def _normalize_allowed_host(value: str) -> str:
    entry = value.strip().lower()
    if not entry:
        raise ValueError("Host allowlist entries must not be empty.")
    if any(char.isspace() for char in entry) or any(char in entry for char in "/?#@"):
        raise ValueError(f"Invalid host allowlist entry: {value!r}")

    try:
        parsed = urlsplit(f"http://{entry}")
        hostname = parsed.hostname
        port = parsed.port
    except ValueError as exc:
        raise ValueError(f"Invalid host allowlist entry: {value!r}") from exc

    if hostname is None:
        raise ValueError(f"Invalid host allowlist entry: {value!r}")

    normalized_host = f"[{hostname}]" if ":" in hostname else hostname
    if port is not None:
        return f"{normalized_host}:{port}"
    return normalized_host


def _normalize_allowed_origin(value: str) -> str:
    origin = value.strip()
    if not origin:
        raise ValueError("Origin allowlist entries must not be empty.")

    try:
        parsed = urlsplit(origin)
    except ValueError as exc:
        raise ValueError(f"Invalid origin allowlist entry: {value!r}") from exc

    if parsed.scheme not in {"http", "https"} or parsed.hostname is None:
        raise ValueError(f"Invalid origin allowlist entry: {value!r}")
    if parsed.path not in {"", "/"} or parsed.query or parsed.fragment or parsed.username or parsed.password:
        raise ValueError(f"Invalid origin allowlist entry: {value!r}")

    default_port = 80 if parsed.scheme == "http" else 443
    host = f"[{parsed.hostname}]" if ":" in parsed.hostname else parsed.hostname
    if parsed.port in {None, default_port}:
        return f"{parsed.scheme}://{host}"
    return f"{parsed.scheme}://{host}:{parsed.port}"


