def _xdg_path(env_var: str, fallback: Path) -> Path:
    """Returns an XDG directory override or the given fallback path."""
    value = os.environ.get(env_var)
    if value:
        return Path(value)
    return fallback


def get_config_file_path() -> Path:
    """Returns the XDG-compliant path to the user settings file.

    Uses ``$XDG_CONFIG_HOME/janus/settings.toml`` when ``XDG_CONFIG_HOME`` is
    set; otherwise falls back to ``~/.config/janus/settings.toml``.
    """
    return get_config_dir() / "settings.toml"


def get_config_dir() -> Path:
    """Returns the XDG-compliant directory for Janus user configuration."""
    return _xdg_path("XDG_CONFIG_HOME", Path.home() / ".config") / "janus"


def get_data_dir() -> Path:
    """Returns the XDG-compliant persistent data directory for Janus."""
    return _xdg_path("XDG_DATA_HOME", Path.home() / ".local" / "share") / "janus"


def get_state_dir() -> Path:
    """Returns the XDG-compliant persistent state directory for Janus."""
    return _xdg_path("XDG_STATE_HOME", Path.home() / ".local" / "state") / "janus"


def get_default_database_url() -> str:
    """Returns the default SQLite database URL at a persistent absolute path."""
    return f"sqlite:///{get_data_dir() / 'janus.db'}"


def get_default_fernet_key_path() -> Path:
    """Returns the default absolute path of the Fernet key file."""
    return get_data_dir() / ".janus_key"


def get_default_image_storage_dir() -> Path:
    """Returns the default absolute directory for chat-generated images (JAN-253)."""
    return get_data_dir() / "images"


def get_default_log_file_path() -> Path:
    """Returns the default absolute path of the Janus runtime log file."""
    return get_state_dir() / "janus.log"


