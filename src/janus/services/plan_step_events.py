"""Live plan/step events of one chat turn (JAN-316).

A chat turn is one runtime plan step (``PreparedStep.step``). Inside it the
tool-calling agent works in rounds: every model call that asks for tools is
one *turn step*, and the tools it asked for run under it. :class:`TurnEventStream`
turns LangChain ``astream_events`` v2 events into the turn's frames:

* ``__TOOL_EVENT__:<json>`` (JAN-249, :mod:`janus.services.tool_call_events`),
  each now carrying the ``step_id`` of the step the call ran in;
* ``__PLAN_EVENT__:<json>`` (:class:`PlanStepEvent`) for each step's
  lifecycle: ``pending`` (generated by the model), ``running`` (right before
  its first call starts), then ``completed`` or ``failed``.

The status names are :class:`janus.plan_graph.PlanStepStatus` values, so the
in-chat timeline and the persisted plan surfaces (JAN-204) share one
vocabulary. "Waiting for approval" is not a frame: clients derive it from a
step's unanswered ``__TOOL_APPROVAL__`` requests (JAN-254).

Steps are live only; nothing here is persisted. :func:`chunk_text` reads
the reply text of the same stream's model chunks, and :class:`RoundTextJoiner`
(``TurnEventStream.text``) keeps each round's text a separate paragraph.
"""

from __future__ import annotations

import json
import time
from collections.abc import Callable, Mapping
from dataclasses import asdict, dataclass, field
from typing import Any

from janus.plan_graph import PlanStepStatus
from janus.services import tool_call_events

PLAN_EVENT_PREFIX = "__PLAN_EVENT__:"

#: A step fails when any of its calls ended in one of these phases.
_FAILED_CALL_PHASES = frozenset({tool_call_events.PHASE_ERROR, tool_call_events.PHASE_BLOCKED})


@dataclass
class PlanStepEvent:
    """One ``__PLAN_EVENT__`` frame: the state of one turn step."""

    step_id: str
    index: int
    status: str
    tool_names: list[str] = field(default_factory=list)

    def to_marker(self) -> str:
        """Return the frame streamed to chat clients."""
        return PLAN_EVENT_PREFIX + json.dumps(asdict(self), ensure_ascii=False)


def parse_marker(token: str) -> PlanStepEvent | None:
    """Return the event a ``__PLAN_EVENT__`` frame carries, or ``None`` for anything else."""
    if not token.startswith(PLAN_EVENT_PREFIX):
        return None
    try:
        payload = json.loads(token[len(PLAN_EVENT_PREFIX) :])
        return PlanStepEvent(**payload)
    except (TypeError, ValueError):
        return None


def requested_tool_names(output: Any) -> list[str]:
    """Return the tool names a model round asked for (its message's ``tool_calls``), in order."""
    calls = output.get("tool_calls") if isinstance(output, Mapping) else getattr(output, "tool_calls", None)
    names = []
    for call in calls or ():
        name = call.get("name") if isinstance(call, Mapping) else getattr(call, "name", None)
        if isinstance(name, str) and name:
            names.append(name)
    return names


def chunk_text(chunk: Any) -> str:
    """Return the reply text of one ``on_chat_model_stream`` chunk (a string, or a message's text content parts)."""
    if chunk is None:
        return ""
    if isinstance(chunk, str):
        return chunk
    content = getattr(chunk, "content", None)
    if isinstance(content, str):
        return content
    if not isinstance(content, list):
        return ""
    parts = []
    for item in content:
        text = item if isinstance(item, str) else item.get("text") if isinstance(item, dict) else None
        if isinstance(text, str):
            parts.append(text)
    return "".join(parts)


class RoundTextJoiner:
    """Keeps each agent round's reply text a separate paragraph.

    A plan, its progress notes, and the answer are written in different model
    rounds; streamed back to back they would run together. The first text of a
    round that follows earlier text gets a blank line in front, unless that text
    already ended with one.
    """

    def __init__(self) -> None:
        """Start a turn with no text written."""
        self._tail = ""
        self._break_pending = False

    def round_started(self) -> None:
        """Note that a new agent round began (not a model a tool runs internally)."""
        self._break_pending = bool(self._tail.strip())

    def text(self, text: str) -> str:
        """Return ``text`` with the paragraph break it needs in front, if it opens a round."""
        prefix = ""
        if self._break_pending:
            self._break_pending = False
            if not self._tail.endswith("\n\n"):
                prefix = "\n" if self._tail.endswith("\n") else "\n\n"
        self._tail = (self._tail + text)[-2:]
        return prefix + text


@dataclass
class _OpenStep:
    event: PlanStepEvent
    expected_calls: int
    started_calls: int = 0
    finished_calls: int = 0
    failed: bool = False


class PlanStepTracker:
    """Keeps the turn's open step and returns the ``__PLAN_EVENT__`` frames its changes produce."""

    def __init__(self) -> None:
        """Start a turn with no steps."""
        self._count = 0
        self._open: _OpenStep | None = None

    @property
    def current_step_id(self) -> str | None:
        """Return the id of the open step, or ``None`` between steps."""
        return self._open.event.step_id if self._open is not None else None

    def _emit(self, status: PlanStepStatus) -> str:
        assert self._open is not None
        self._open.event.status = status.value
        return self._open.event.to_marker()

    def _begin(self, tool_names: list[str]) -> list[str]:
        self._count += 1
        event = PlanStepEvent(step_id=f"step-{self._count}", index=self._count, status=PlanStepStatus.PENDING.value)
        event.tool_names = list(tool_names)
        self._open = _OpenStep(event=event, expected_calls=len(tool_names))
        return [self._emit(PlanStepStatus.PENDING)]

    def close(self, *, failed: bool = False) -> list[str]:
        """Close the open step (``failed`` when it or the stream failed); no frame when none is open."""
        if self._open is None:
            return []
        status = PlanStepStatus.FAILED if failed or self._open.failed else PlanStepStatus.COMPLETED
        frame = self._emit(status)
        self._open = None
        return [frame]

    def model_ended(self, output: Any) -> list[str]:
        """Open a ``pending`` step when a model round asked for tools (closing any step still open)."""
        tool_names = requested_tool_names(output)
        if not tool_names:
            return []
        return [*self.close(), *self._begin(tool_names)]

    def call_started(self) -> list[str]:
        """Mark the open step ``running`` on its first call (opening an implicit step when none is open)."""
        frames = self._begin([]) if self._open is None else []
        assert self._open is not None
        self._open.started_calls += 1
        if self._open.started_calls == 1:
            frames.append(self._emit(PlanStepStatus.RUNNING))
        return frames

    def call_finished(self, phase: str) -> list[str]:
        """Record a finished call; close the step once every call the model asked for finished."""
        if self._open is None:
            return []
        self._open.finished_calls += 1
        self._open.failed = self._open.failed or phase in _FAILED_CALL_PHASES
        if self._open.expected_calls and self._open.finished_calls >= self._open.expected_calls:
            return self.close()
        return []


class TurnEventStream:
    """Turns one turn's LangChain stream events into ``__TOOL_EVENT__`` and ``__PLAN_EVENT__`` frames.

    Model events while a tool call is open come from a model a tool runs
    internally, not from an agent round, and are ignored.
    """

    def __init__(self, clock: Callable[[], float] = time.monotonic) -> None:
        """Track the turn's steps and tool calls, timing calls with ``clock`` (seconds)."""
        self.steps = PlanStepTracker()
        self.tools = tool_call_events.ToolEventTracker(clock, step_id=lambda: self.steps.current_step_id)
        self.text = RoundTextJoiner()

    def observe(self, event: Mapping[str, Any]) -> list[str]:
        """Return the frames one ``astream_events`` v2 event produces, in streaming order."""
        kind = event.get("event")
        if kind in ("on_chat_model_start", "on_chat_model_end"):
            if self.tools.has_open_calls:
                return []
            if kind == "on_chat_model_start":
                self.text.round_started()
                return self.steps.close()
            return self.steps.model_ended((event.get("data") or {}).get("output"))
        if kind not in tool_call_events.TOOL_EVENT_HANDLERS or not event.get("name"):
            return []
        if kind == "on_tool_start" and not self.tools.is_nested(event):
            # The step is running (or implicitly opened) before its call's start frame.
            prefix = self.steps.call_started()
            marker = self.tools.start(event)
            return [*prefix, marker] if marker is not None else prefix
        marker = getattr(self.tools, tool_call_events.TOOL_EVENT_HANDLERS[kind])(event)
        if marker is None:
            return []
        finished = tool_call_events.parse_marker(marker)
        if finished is None or finished.phase not in tool_call_events.TERMINAL_PHASES:
            return [marker]
        return [marker, *self.steps.call_finished(finished.phase)]

    def finish(self, *, failed: bool = False) -> list[str]:
        """Return the frame closing a step still open when the stream ends (``failed`` on a stream error)."""
        return self.steps.close(failed=failed)


